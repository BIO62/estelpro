export function matchAimag(city?: string | null) {
  const t = (city || '').trim();
  if (!t || t === 'Улаанбаатар' || t === 'УБ') return 'Улаанбаатар хот';
  const exact = AIMAGS.find((a) => a === t);
  if (exact) return exact;
  const found = AIMAGS.find((a) => t.includes(a.replace(' аймаг', '').replace(' хот', '')) || a.includes(t));
  return found || t;
}

export function districtsForCity(city?: string | null) {
  return DISTRICTS_BY_AIMAG[matchAimag(city)] || [];
}

/** Demo delivery fee by bag/district (GreenSoft getdevprice stand-in) */
export function getDeliveryPrice(district: string, bag: string): number {
  if (!district && !bag) return 0;
  if (district === 'Улаанбаатар хот' || DISTRICTS_BY_AIMAG['Улаанбаатар хот']?.includes(district)) {
    return 5000;
  }
  return 15000;
}
